"""
CoreProfile Report Builder
Handles the presentation layer of the tool. It takes the raw statistical
data generated by the backend and injects it into a Jinja2 HTML template
to produce the final interactive dashboard.
"""

import os
from jinja2 import Environment, FileSystemLoader

def build_report(data: dict, output_path: str, template_name: str = "report_base.html"):
    """
    Renders an HTML report by injecting statistical data into a Jinja2 template.
    
    Args:
        data (dict): The parsed JSON statistics containing metadata and column metrics.
        output_path (str): The file path where the generated HTML report will be saved.
        template_name (str): The name of the Jinja2 template file to use.
        
    Raises:
        FileNotFoundError: If the specified template cannot be located in the templates directory.
    """
    
    # Determine the absolute path to the 'templates' directory relative to this script
    current_dir = os.path.dirname(os.path.abspath(__file__))
    templates_dir = os.path.join(current_dir, "templates")
    
    # Initialize the Jinja2 environment with the detected templates folder
    env = Environment(loader=FileSystemLoader(templates_dir))
    
    # Attempt to load the requested HTML template
    try:
        template = env.get_template(template_name)
    except Exception as e:
        raise FileNotFoundError(f"Could not find template '{template_name}' in {templates_dir}. Error: {e}")
    
    # Render the template by passing the statistics dictionary (accessible as 'data' in Jinja)
    html_content = template.render(data=data)
    
    # Write the rendered HTML content to disk with UTF-8 encoding
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html_content)
        
    print(f"📊 Visual report successfully generated at: {output_path}")